export function languageBank(language: Language, tier: Tier) {
  const code = snippets[language === 'typescript' ? 'javascript' : language];
  const authored: Record<Language, TierDrills> = {
    javascript,
    typescript,
    python,
    java,
    go,
    csharp,
  };
  const selected = authored[language][tier];
  const core = [0, 1, 5, 8, 9, 10].map((i) => ({
    ...tasks[i],
    id: `lang-v3-${language}-core-${i}`,
    code: code[i],
  }));
  const offsets = [0, 2, 1, 2, 0, 2];
  return bank([
    ...core,
    ...selected.map(([id, topic, prompt, code, options, reasons], i): Item => {
      const answer = offsets[i];
      const rotate = (values: Four): Four =>
        [...values.slice(4 - answer), ...values.slice(0, 4 - answer)] as Four;
      return {
        id: `lang-v3-${language}-${tier}-${id}`,
        topic: `language-${language}-${topic}`,
        prompt,
        code,
        options: rotate(options),
        reasons: rotate(reasons),
        answer,
      };
    }),
  ]);
}

